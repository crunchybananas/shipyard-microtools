import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {chromium} from '@playwright/test';
import {ensureServer} from './_serve.mjs';
const server=await ensureServer();
const browser=await chromium.launch({headless:process.env.HEADED!=='1'});
const proof=fileURLToPath(new URL('../tmp/lazy-sprite-lab/',import.meta.url));
await mkdir(proof,{recursive:true});
const context=await browser.newContext({viewport:{width:1440,height:900}});
try {
 const page=await context.newPage(),requests=[],errors=[];
 page.on('request',r=>requests.push(r.url()));page.on('pageerror',e=>errors.push(e.message));
 const labRequests=()=>requests.filter(u=>/actors-compiled\/|actor-rows\/manifest\.json/.test(u));
 await page.goto(server.gameUrl);await page.waitForFunction(()=>typeof window.openSpriteLab==='function'&&window.G);
 assert.equal(await page.locator('#sl-list').locator(':scope > *').count(),0);
 assert.deepEqual(labRequests(),[],'closed inspection tool loaded source assets during ordinary startup');
 await page.locator('#title-screen .title-btn.primary').click();
 await page.waitForFunction(()=>!document.body.classList.contains('title-active'));
 await page.waitForTimeout(650);
 await page.screenshot({path:proof+'ordinary-opening.png'});
 const sheet=page.waitForResponse(r=>r.url().includes('actors-compiled/miner.png'));
 await page.evaluate(()=>window.openSpriteLab());
 await page.waitForFunction(()=>document.querySelector('#sl-list').children.length===224);
 await (await sheet).finished();
 assert.equal(await page.locator('#sprite-lab').getAttribute('aria-hidden'),'false');
 assert.equal(labRequests().filter(u=>u.includes('manifest.json')).length,1);
 await page.screenshot({path:proof+'explicit-open.png'});
 const count=labRequests().length;
 await page.evaluate(()=>{window.toggleSpriteLab(false);window.openSpriteLab()});
 await page.waitForTimeout(100);
 assert.equal(labRequests().length,count,'reopening rebuilt or refetched the inspection tool');
 assert.deepEqual(errors,[]);
 const deep=await context.newPage();
 const url=new URL(server.gameUrl);url.searchParams.set('spritelab','1');
 await deep.goto(url.href);
 await deep.waitForFunction(()=>document.body.classList.contains('sprite-lab-open')&&document.querySelector('#sl-list').children.length===224);
 await deep.close();
 console.log('[sprite-lab-lazy-browser] PASS — zero closed-tool rows/requests; first-open, reopen and deep link remain functional');
} finally {await context.close();await browser.close();await server.stop();}
